// Muted UI test of sign up (email -> code -> username + password) and log in (email + password).
const { app, BrowserWindow } = require('electron');
const fs = require('fs');
const path = require('path');
fs.mkdirSync(path.join(__dirname, 'shots'), { recursive: true });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
app.whenReady().then(async () => {
  const errors = [];
  const mk = async (tag) => {
    const win = new BrowserWindow({ show: false, width: 1280, height: 720, useContentSize: true, webPreferences: { offscreen: true, partition: tag + Date.now() } });
    win.webContents.setAudioMuted(true);
    require('./no-voice-ask')(win); // not a voice chat test
    win.webContents.on('console-message', (e, level, msg) => { if (level >= 2) errors.push(msg); });
    await win.loadURL('http://localhost:8781/');
    const js = (code) => win.webContents.executeJavaScript(code);
    await js(`localStorage.setItem('cogwild.profile', JSON.stringify({ xp: 500, coins: 40, settings: { tutorialDone: true, music: 0, sfx: 0 } })); location.reload();`);
    await wait(4500);
    return { win, js, shot: async (name) => fs.writeFileSync(path.join(__dirname, 'shots', name + '.png'), (await win.webContents.capturePage()).toPNG()) };
  };
  const st = (js) => js(`(() => { const v = (id) => !document.getElementById(id).classList.contains('hidden'); return { acct: v('acct'), required: document.getElementById('acct').classList.contains('required'), view: (window.game||CW.game).account.view, err: document.getElementById('acctErr').textContent, me: (window.game||CW.game).account.me && (window.game||CW.game).account.me.name }; })()`);
  const A = await mk('a');
  console.log('START', JSON.stringify(await st(A.js)));
  await A.shot('login-a-login');
  await A.js(`document.getElementById('tabSign').click(); true`);
  await wait(300);
  const mail = 'tester' + (Date.now() % 100000) + '@outlook.com';
  await A.js(`document.getElementById('suEmail').value = '${mail}'; document.querySelector('#fMail .btn').click(); true`);
  await wait(1500);
  console.log('CODE', JSON.stringify(await st(A.js)), 'code filled:', await A.js(`document.getElementById('suCode').value`));
  await A.shot('login-b-code');
  await A.js(`document.querySelector('#fCode .btn').click(); true`);
  await wait(1200);
  console.log('NAME', JSON.stringify(await st(A.js)));
  await A.js(`document.getElementById('suName').value = 'Tester${Date.now() % 1000}'; document.getElementById('suPass').value = 'abcdef1'; document.getElementById('suPass2').value = 'abcdef2'; document.querySelector('#fName .btn').click(); true`);
  await wait(300);
  console.log('MISMATCH', (await st(A.js)).err);
  await A.shot('login-c-name');
  await A.js(`document.getElementById('suPass2').value = 'abcdef1'; document.querySelector('#fName .btn').click(); true`);
  await wait(2500);
  const done = await st(A.js);
  console.log('SIGNED UP', JSON.stringify(done));
  await A.js(`(window.game||CW.game).account.logout(); true`);
  await wait(5000);
  console.log('AFTER LOGOUT', JSON.stringify(await st(A.js)));
  await A.js(`document.getElementById('liEmail').value = '${mail}'; document.getElementById('liPass').value = 'abcdef1'; document.querySelector('#fLogin .btn').click(); true`);
  await wait(2500);
  console.log('LOGGED IN', JSON.stringify(await st(A.js)));
  console.log('errors', errors.length, errors.slice(0, 5).join(' | '));
  app.exit(0);
});
